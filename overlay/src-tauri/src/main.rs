/// OCR the primary monitor and return the recognised lines whose centre falls inside a `w*h`
/// box centred on (`cx`,`cy`) — the caller passes the cursor so the hovered node's tooltip is
/// captured wherever it flips to. Centres are in full-frame physical px; the caller fuzzy-
/// matches the lines against the jewel's result-notable vocabulary.
///
/// We OCR the *whole frame* and then drop out-of-box lines by coordinate, rather than feeding
/// OCR a cropped or masked buffer. Two reasons, both observed on real captures:
///   1. Windows.Media.Ocr rescales its input by the image's overall dimensions before
///      recognition. A cropped buffer (seen at exactly 1400x1200) lands otherwise-crisp
///      tooltip text on a bad internal scale and returns noise; the full frame reads reliably.
///   2. Masking everything outside the box to black is itself a different image and triggers
///      the same fragility — it was observed to make OCR *drop* the real tooltip line while a
///      stale word from the overlay's status panel survived. Filtering by coordinate after a
///      clean full-frame OCR avoids both: the engine always sees the same crisp full frame,
///      and box membership is decided on the returned line centres.
///
/// Box membership is the only gate here. The caller still excludes its own panel region (it
/// knows the panel's live bounds) before matching, so panel text inside the box can't inject
/// false vocabulary matches.
#[tauri::command]
fn ocr_region(cx: f64, cy: f64, w: f64, h: f64) -> Result<Vec<OcrLine>, String> {
    let (frame, fw, fh) = capture_primary()?;
    // Windows OCR wants BGRA8; xcap gives RGBA8, so swap R/B across the whole frame.
    let n = (fw as usize) * (fh as usize);
    let mut bgra = vec![0u8; n * 4];
    for i in 0..n {
        bgra[i * 4] = frame[i * 4 + 2];
        bgra[i * 4 + 1] = frame[i * 4 + 1];
        bgra[i * 4 + 2] = frame[i * 4];
        bgra[i * 4 + 3] = frame[i * 4 + 3];
    }
    let lines = ocr::recognize(&bgra, fw, fh)?;
    // Keep lines whose centre lands in the cursor box (coords are already full-frame px).
    let (x0, y0) = (cx - w / 2.0, cy - h / 2.0);
    let (x1, y1) = (cx + w / 2.0, cy + h / 2.0);
    Ok(lines
        .into_iter()
        .filter(|l| l.cx >= x0 && l.cx <= x1 && l.cy >= y0 && l.cy <= y1)
        .collect())
}

/// POST a batch of recorded observations (serialised by the frontend) to the Worker write
/// endpoint. Done here rather than in the webview because the overlay's CSP blocks
/// cross-origin fetch; from native code there's no CORS to satisfy. Returns the Worker's
/// JSON body on success so the frontend can read accepted/rejected counts; a non-2xx
/// status is surfaced as an error so the frontend keeps the batch pending for retry.
#[tauri::command]
async fn submit_observations(worker_url: String, body: String) -> Result<String, String> {
    let url = format!("{}/api/poe2/observations", worker_url.trim_end_matches('/'));
    let resp = reqwest::Client::new()
        .post(&url)
        .header("Content-Type", "application/json")
        .body(body)
        .send()
        .await
        .map_err(|e| e.to_string())?;
    let status = resp.status();
    let text = resp.text().await.unwrap_or_default();
    if !status.is_success() {
        return Err(format!("HTTP {}: {}", status.as_u16(), text));
    }
    Ok(text)
}

/// Fetch the community consensus for a (jewel, seed) from the Worker so the overlay can show
/// which nodes are already recorded/verified and skip them. A GET from native code (no CORS),
/// same reason as submit_observations. Returns the Worker's JSON body.
#[tauri::command]
async fn fetch_consensus(worker_url: String, jewel: String, seed: u32) -> Result<String, String> {
    let seed_s = seed.to_string();
    let resp = reqwest::Client::new()
        .get(format!("{}/api/poe2/consensus", worker_url.trim_end_matches('/')))
        .query(&[("jewel", jewel.as_str()), ("seed", seed_s.as_str())])
        .send()
        .await
        .map_err(|e| e.to_string())?;
    let status = resp.status();
    let text = resp.text().await.unwrap_or_default();
    if !status.is_success() {
        return Err(format!("HTTP {}: {}", status.as_u16(), text));
    }
    Ok(text)
}

/// Type a search string into whatever window currently has focus — used to drive the in-game
/// passive-tree search during an auto-sweep. The contributor clicks the search box once (so PoE2
/// holds keyboard focus); the click-through, no-activate overlay never steals it, so these
/// synthetic keystrokes land in the game. First clears the field (Ctrl+A then Delete), then types
/// `text` as Unicode (KEYEVENTF_UNICODE) so arbitrary characters — apostrophes in names like
/// "Mercenary's Lot" — type correctly regardless of keyboard layout. The whole sequence is one
/// SendInput batch (atomic w.r.t. other input). NOTE: this is opt-in (an explicit sweep hotkey),
/// never automatic — the contributor must focus the search box first or the keystrokes hit the game.
#[tauri::command]
fn type_search(text: String) -> Result<(), String> {
    use windows::Win32::UI::Input::KeyboardAndMouse::{
        SendInput, INPUT, INPUT_0, INPUT_KEYBOARD, KEYBDINPUT, KEYBD_EVENT_FLAGS, KEYEVENTF_KEYUP,
        KEYEVENTF_UNICODE, VIRTUAL_KEY, VK_A, VK_CONTROL, VK_DELETE,
    };
    fn vk(code: VIRTUAL_KEY, flags: KEYBD_EVENT_FLAGS) -> INPUT {
        INPUT {
            r#type: INPUT_KEYBOARD,
            Anonymous: INPUT_0 {
                ki: KEYBDINPUT { wVk: code, wScan: 0, dwFlags: flags, time: 0, dwExtraInfo: 0 },
            },
        }
    }
    fn unicode(unit: u16, up: bool) -> INPUT {
        let flags = if up { KEYEVENTF_UNICODE | KEYEVENTF_KEYUP } else { KEYEVENTF_UNICODE };
        INPUT {
            r#type: INPUT_KEYBOARD,
            Anonymous: INPUT_0 {
                ki: KEYBDINPUT { wVk: VIRTUAL_KEY(0), wScan: unit, dwFlags: flags, time: 0, dwExtraInfo: 0 },
            },
        }
    }
    let down = KEYBD_EVENT_FLAGS(0);
    let mut inputs: Vec<INPUT> = Vec::with_capacity(text.len() * 2 + 6);
    // Clear the field: Ctrl+A (select all) then Delete.
    inputs.push(vk(VK_CONTROL, down));
    inputs.push(vk(VK_A, down));
    inputs.push(vk(VK_A, KEYEVENTF_KEYUP));
    inputs.push(vk(VK_CONTROL, KEYEVENTF_KEYUP));
    inputs.push(vk(VK_DELETE, down));
    inputs.push(vk(VK_DELETE, KEYEVENTF_KEYUP));
    // Type the text as UTF-16 code units (down+up per unit).
    for u in text.encode_utf16() {
        inputs.push(unicode(u, false));
        inputs.push(unicode(u, true));
    }
    let sent = unsafe { SendInput(&inputs, std::mem::size_of::<INPUT>() as i32) };
    if sent as usize != inputs.len() {
        return Err(format!(
            "SendInput delivered {sent}/{} events — input may be blocked (run PoE2 and the overlay at the same privilege level).",
            inputs.len()
        ));
    }
    Ok(())
}

