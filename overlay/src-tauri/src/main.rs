/// Parsed from the jewel's Ctrl+C item text. The seed is what makes a recording
/// meaningful — the same node in the same socket transforms differently per seed.
#[derive(Serialize, Clone)]
struct JewelInfo {
    /// "Heroic Tragedy" | "Undying Hate".
    jewel: String,
    seed: u32,
    /// The selected conqueror, e.g. "Vorana" (empty if not found).
    conqueror: String,
}

/// The seed is the integer immediately followed by its "(min-max)" range, e.g.
/// `Remembrancing 7704(100-8000) ...`. Scanning for that pattern is robust across
/// both jewels regardless of the surrounding flavour wording.
///
/// With PoE's "Advanced Mod Descriptions" enabled, enchant/implicit rolls ALSO copy
/// with a parenthetical range — e.g. `+6(4-8) to Intelligence` — and such a line can
/// sit above the seed line. So we collect every `number(min-max)` candidate and keep
/// the one whose range span (`max - min`) is widest: a timeless-jewel seed range spans
/// thousands (100-8000, 79-30977) while a stat roll spans single digits, so the seed
/// always wins without hardcoding any per-jewel range.
fn find_seed(text: &str) -> Option<u32> {
    let b = text.as_bytes();
    let n = b.len();
    let mut i = 0;
    let mut best: Option<(u32, u32)> = None; // (seed, range span)
    while i < n {
        if !b[i].is_ascii_digit() {
            i += 1;
            continue;
        }
        let start = i;
        while i < n && b[i].is_ascii_digit() {
            i += 1;
        }
        // Require "(min-max)" immediately after the number.
        if i < n && b[i] == b'(' {
            let mut j = i + 1;
            let ds = j;
            while j < n && b[j].is_ascii_digit() {
                j += 1;
            }
            if j > ds && j < n && b[j] == b'-' {
                let min: Option<u32> = text[ds..j].parse().ok();
                j += 1;
                let es = j;
                while j < n && b[j].is_ascii_digit() {
                    j += 1;
                }
                if j > es && j < n && b[j] == b')' {
                    if let (Some(seed), Some(min), Some(max)) =
                        (text[start..i].parse::<u32>().ok(), min, text[es..j].parse::<u32>().ok())
                    {
                        let span = max.saturating_sub(min);
                        if best.map_or(true, |(_, b_span)| span > b_span) {
                            best = Some((seed, span));
                        }
                    }
                }
            }
        }
    }
    best.map(|(seed, _)| seed)
}

/// The selected conqueror from "...by the line of <Name>(<all variants>)".
fn find_conqueror(text: &str) -> Option<String> {
    const KEY: &str = "by the line of ";
    let p = text.find(KEY)? + KEY.len();
    let rest = &text[p..];
    let end = rest.find('(').unwrap_or(rest.len());
    let name = rest[..end].trim();
    (!name.is_empty()).then(|| name.to_string())
}

/// Parse a PoE2 timeless-jewel item-text clipboard string. Returns None if the text
/// isn't a timeless jewel or has no recognisable seed.
fn parse_jewel(text: &str) -> Option<JewelInfo> {
    if !text.contains("Timeless Jewel") {
        return None;
    }
    let lines: Vec<&str> = text.lines().map(|l| l.trim()).collect();
    // The jewel name is the line directly above "Timeless Jewel".
    let idx = lines.iter().position(|&l| l == "Timeless Jewel")?;
    if idx == 0 {
        return None;
    }
    let jewel = lines[idx - 1].to_string();
    let seed = find_seed(text)?;
    Some(JewelInfo {
        jewel,
        seed,
        conqueror: find_conqueror(text).unwrap_or_default(),
    })
}

/// Capture the primary monitor as raw RGBA8 (`w*h*4` bytes, row-major). Serialises on
/// CAPTURE_LOCK because xcap's Windows DXGI path crashes if two captures overlap. The
/// single capture path for everything that needs pixels (detect + OCR).
fn capture_primary() -> Result<(Vec<u8>, u32, u32), String> {
    let _guard = CAPTURE_LOCK.lock().map_err(|_| "capture lock poisoned")?;
    let monitors = xcap::Monitor::all().map_err(|e| e.to_string())?;
    let monitor = monitors
        .into_iter()
        .find(|m| m.is_primary())
        .ok_or("no primary monitor")?;
    let img = monitor.capture_image().map_err(|e| e.to_string())?;
    let (w, h) = (img.width(), img.height());
    Ok((img.into_raw(), w, h))
}

fn graphs() -> &'static GraphData {
    use std::sync::OnceLock;
    static D: OnceLock<GraphData> = OnceLock::new();
    D.get_or_init(|| serde_json::from_str(SOCKET_GRAPHS_JSON).expect("valid poe2_socket_graphs.json"))
}

/// Sobel gradient-magnitude edge bitmap (true = edge pixel) over the RGBA capture.
/// Edges are the jewel-art-INDEPENDENT signal: node positions and the connector
/// lines between them don't change under a timeless jewel, so the tree's line
/// structure is a stable fingerprint. Threshold mirrors the offline harness
/// (Sobel magnitude > ~200 on 0..255 luminance), validated against `Screenshots/`.
fn edge_map(buf: &[u8], w: usize, h: usize, thr: f64) -> Vec<bool> {
    let mut lum = vec![0f32; w * h];
    for i in 0..w * h {
        let p = i * 4;
        lum[i] = (buf[p] as f32 + buf[p + 1] as f32 + buf[p + 2] as f32) / 3.0;
    }
    let mut edge = vec![false; w * h];
    for y in 1..h - 1 {
        for x in 1..w - 1 {
            let i = y * w + x;
            let (tl, tc, tr) = (lum[i - w - 1], lum[i - w], lum[i - w + 1]);
            let (ml, mr) = (lum[i - 1], lum[i + 1]);
            let (bl, bc, br) = (lum[i + w - 1], lum[i + w], lum[i + w + 1]);
            let gx = (tr + 2.0 * mr + br) - (tl + 2.0 * ml + bl);
            let gy = (bl + 2.0 * bc + br) - (tl + 2.0 * tc + tr);
            if ((gx * gx + gy * gy).sqrt() as f64) > thr {
                edge[i] = true;
            }
        }
    }
    edge
}

/// Two-pass chamfer distance transform: each cell holds the approximate distance
/// (in pixels) to the nearest edge pixel. 3-4 chamfer weights approximate
/// Euclidean distance; dividing by 3 converts the integer weights to ~pixel units.
/// This lets us score a projected model against the edge map with one lookup per
/// sample — robust to faint/broken lines because near-misses still score low.
fn distance_transform(edge: &[bool], w: usize, h: usize) -> Vec<f32> {
    const BIG: f32 = 1e9;
    const D3: f32 = 3.0;
    const D4: f32 = 4.0;
    let mut d = vec![BIG; w * h];
    for i in 0..w * h {
        if edge[i] {
            d[i] = 0.0;
        }
    }
    for y in 0..h {
        for x in 0..w {
            let i = y * w + x;
            let mut v = d[i];
            if x > 0 {
                v = v.min(d[i - 1] + D3);
            }
            if y > 0 {
                v = v.min(d[i - w] + D3);
                if x > 0 {
                    v = v.min(d[i - w - 1] + D4);
                }
                if x + 1 < w {
                    v = v.min(d[i - w + 1] + D4);
                }
            }
            d[i] = v;
        }
    }
    for y in (0..h).rev() {
        for x in (0..w).rev() {
            let i = y * w + x;
            let mut v = d[i];
            if x + 1 < w {
                v = v.min(d[i + 1] + D3);
            }
            if y + 1 < h {
                v = v.min(d[i + w] + D3);
                if x + 1 < w {
                    v = v.min(d[i + w + 1] + D4);
                }
                if x > 0 {
                    v = v.min(d[i + w - 1] + D4);
                }
            }
            d[i] = v;
        }
    }
    for v in d.iter_mut() {
        *v /= 3.0;
    }
    d
}

/// Mean chamfer distance of a socket's projected connector EDGES to the captured
/// edge map. Each edge is sampled every ~6px and the distance-transform value
/// under each sample is averaged; samples projected outside the ring/frame are
/// skipped. The correct socket's edges align with real tree lines, so its mean
/// distance is the LOWEST. (Replaces the old node-brightness heuristic, which the
/// jewel's changed node art made unreliable.)
fn score_socket_edges(
    dt: &[f32],
    w: usize,
    h: usize,
    cx: f64,
    cy: f64,
    r: f64,
    r_tree: f64,
    sock: &SocketGraphT,
) -> f64 {
    let s = r / r_tree;
    let step = 6.0;
    let mut sum = 0.0;
    let mut n = 0usize;
    for e in &sock.edges {
        let ax = cx + (e[0] - sock.x) * s;
        let ay = cy + (e[1] - sock.y) * s;
        let bx = cx + (e[2] - sock.x) * s;
        let by = cy + (e[3] - sock.y) * s;
        let seg = ((bx - ax).powi(2) + (by - ay).powi(2)).sqrt();
        let steps = (seg / step).max(2.0) as usize;
        for k in 0..=steps {
            let t = k as f64 / steps as f64;
            let px = ax + (bx - ax) * t;
            let py = ay + (by - ay) * t;
            if ((px - cx).powi(2) + (py - cy).powi(2)).sqrt() > r {
                continue;
            }
            let (ix, iy) = (px as i64, py as i64);
            if ix < 0 || iy < 0 || ix as usize >= w || iy as usize >= h {
                continue;
            }
            sum += dt[iy as usize * w + ix as usize] as f64;
            n += 1;
        }
    }
    if n == 0 {
        1e9
    } else {
        sum / n as f64
    }
}

/// Refine the pose (centre + radius) by minimising the edge-chamfer cost of the identified
/// socket's projected connector edges against the captured tree lines. The gem template gives
/// a good centre and an approximate scale; this snaps both to the real tree geometry so the
/// projected notables overlay the actual nodes (fixes residual off-centre / scale error). Two
/// shrinking grid passes (coarse → fine); cheap enough for the one-shot calibrate.
fn refine_pose(
    dt: &[f32],
    w: usize,
    h: usize,
    cx: f64,
    cy: f64,
    r: f64,
    r_tree: f64,
    sock: &SocketGraphT,
) -> (f64, f64, f64) {
    let (mut bcx, mut bcy, mut br) = (cx, cy, r);
    let mut bc = score_socket_edges(dt, w, h, bcx, bcy, br, r_tree, sock);
    // (offset step px, offset max px, scale step, scale steps each side)
    for &(off_step, off_max, sc_step, sc_n) in &[(4i64, 8i64, 0.03f64, 3i64), (1i64, 3i64, 0.01f64, 3i64)] {
        let (c0x, c0y, r0) = (bcx, bcy, br);
        let mut si = -sc_n;
        while si <= sc_n {
            let rr = r0 * (1.0 + sc_step * si as f64);
            let mut dy = -off_max;
            while dy <= off_max {
                let mut dx = -off_max;
                while dx <= off_max {
                    let (ncx, ncy) = (c0x + dx as f64, c0y + dy as f64);
                    let s = score_socket_edges(dt, w, h, ncx, ncy, rr, r_tree, sock);
                    if s < bc {
                        bc = s;
                        bcx = ncx;
                        bcy = ncy;
                        br = rr;
                    }
                    dx += off_step;
                }
                dy += off_step;
            }
            si += 1;
        }
    }
    (bcx, bcy, br)
}

/// Capture the primary monitor and detect the jewel's radius RING (the coloured circle it draws
/// on the tree). Returns the ring centre, the ring radius in px (the scale anchor: s = r / R_tree),
/// the jewel type (from the ring colour), and which socket it sits in. `None` when no ring is found.
///
/// Detection runs only on an explicit calibrate (one-shot), so the ring's animation jitter is
/// irrelevant. `jewel` (the type the user copied with Ctrl+C, if known) restricts detection to that
/// colour — cheaper and immune to the other colour's UI clutter. `socket_hint` forces the tree-snap
/// to a specific socket (the user's locked choice) instead of re-identifying. `identify` runs the
/// (heavier) socket scoring + tree-snap; pass `false` to skip it (`socket_id` stays -1).
#[tauri::command]
fn capture_and_detect(
    jewel: Option<String>,
    socket_hint: Option<i64>,
    identify: bool,
) -> Result<Option<Detection>, String> {
    let (frame, w, h) = capture_primary()?;
    let buf: &[u8] = &frame;
    let (wu, hu) = (w as usize, h as usize);

    // Detect the radius ring. Restrict to the copied jewel's colour when known (cheaper, and
    // immune to the other colour's UI clutter); otherwise try both and keep the better-supported
    // circle. The ring colour also identifies the jewel type.
    let all = [
        (Jewel::UndyingHate, "Undying Hate"),
        (Jewel::HeroicTragedy, "Heroic Tragedy"),
    ];
    let candidates: Vec<(Jewel, &str)> = match jewel.as_deref() {
        Some(j) if all.iter().any(|&(_, n)| n == j) => all.into_iter().filter(|&(_, n)| n == j).collect(),
        _ => all.to_vec(),
    };
    let mut best: Option<(ring::Circle, &str)> = None;
    for (kind, name) in candidates {
        if let Some(c) = detect(buf, w, h, kind) {
            if best.as_ref().map_or(true, |(bc, _)| c.support > bc.support) {
                best = Some((c, name));
            }
        }
    }
    let Some((c, jewel)) = best else {
        // No colour ring. If a WHITE ring is there instead, the jewel is being hovered (its
        // tooltip is up, recolouring the ring) — signal that so the caller can ask the user to
        // move off it, rather than the generic "can't find socket" dead end.
        if let Some(wc) = ring::detect_white(buf, w, h) {
            if wc.coverage >= 0.5 {
                return Ok(Some(Detection {
                    cx: wc.cx,
                    cy: wc.cy,
                    r: wc.r,
                    support: 0,
                    coverage: wc.coverage,
                    resid: wc.resid,
                    frame_w: w,
                    frame_h: h,
                    jewel: String::new(),
                    jewel_match: 0.0,
                    gem: 0.0,
                    socket_id: -1,
                    socket_score: 0.0,
                    socket_second: 0.0,
                    hovered: true,
                }));
            }
        }
        return Ok(None);
    };
    // The ring fit IS the pose: centre = the socket's projected position, radius = R_tree px,
    // so the projection scale s = r / R_tree is exact. `refine_pose` polishes it against the tree.
    let (mut cx, mut cy, mut r) = (c.cx, c.cy, c.r);
    // Ring coverage (fraction of the circle the masked arc spans) is the confidence the caller
    // gates on — a partial/occluded ring or a stray blob scores low.
    let jewel_match = c.coverage;

    let g = graphs();

    // Identify the socket by edge-chamfer registration over all 12 jewel sockets — only when
    // asked. In the on-demand calibration model this runs on every (explicit) calibrate.
    let (mut socket_id, mut socket_score, mut socket_second) = (-1i64, 0.0f64, 0.0f64);
    if identify {
        let edge = edge_map(buf, wu, hu, 200.0);
        let dt = distance_transform(&edge, wu, hu);
        // Lower chamfer cost = better geometric fit.
        let mut bests = (-1i64, f64::INFINITY);
        let mut second = f64::INFINITY;
        for sock in &g.sockets {
            let sc = score_socket_edges(&dt, wu, hu, cx, cy, r, g.r_tree, sock);
            if sc < bests.1 {
                second = bests.1;
                bests = (sock.socket_id, sc);
            } else if sc < second {
                second = sc;
            }
        }
        socket_score = bests.1;
        socket_second = second;
        // The user's manual socket choice (after they cycled to correct a wrong auto-ID) wins,
        // so the tree-snap below refines for THAT socket; otherwise use the confidence gate:
        // commit only when the runner-up is clearly worse, else stay unresolved (-1).
        match socket_hint {
            Some(hint) if g.sockets.iter().any(|s| s.socket_id == hint) => socket_id = hint,
            _ if bests.1.is_finite() && second.is_finite() && second > bests.1 * 1.06 => {
                socket_id = bests.0;
            }
            _ => {}
        }
        if socket_id >= 0 {
            // Snap the pose (centre + scale) to the chosen socket's actual tree lines.
            // The gem template gives a good seed; this fixes residual off-centre / scale error
            // so the projected notables land on the real nodes. Affordable as a one-shot.
            if let Some(sock) = g.sockets.iter().find(|s| s.socket_id == socket_id) {
                let (ncx, ncy, nr) = refine_pose(&dt, wu, hu, cx, cy, r, g.r_tree, sock);
                cx = ncx;
                cy = ncy;
                r = nr;
                socket_score = score_socket_edges(&dt, wu, hu, cx, cy, r, g.r_tree, sock);
            }
        }
    }

    Ok(Some(Detection {
        cx,
        cy,
        r,
        support: c.support,
        coverage: c.coverage,
        resid: c.resid,
        frame_w: w,
        frame_h: h,
        jewel: jewel.to_string(),
        jewel_match,
        gem: 0.0,
        socket_id,
        socket_score,
        socket_second,
        hovered: false,
    }))
}

// The glow is probed in GLOW_ANGLES directions around the node, each at several radial multiples of
// icon_r (the halo sits at the icon edge and fades outward). A direction counts as "lit" if ANY of
// its radii hits a glow pixel; the node is highlighted when most directions are lit.
const GLOW_ANGLES: usize = 16;
const GLOW_RADII: [f64; 4] = [0.8, 1.0, 1.2, 1.45];
// Fraction of directions that must show glow. The search halo is radially symmetric (~all
// directions), whereas a jewel-ring spoke or a one-sided green sunburst lights only ~1-2. Measured:
// a real lit node covers 16/16 directions, while spokes, coloured sunbursts and unlit nodes all
// cover <=1/16 — so 0.6 sits in a very wide gap.
const GLOW_COVERAGE_MIN: f64 = 0.6;

/// A "glow" pixel: near-grey (channels close together) and clearly above the dark tree background.
/// The PoE2 search highlight is a soft WHITE-GREY halo around the matched node — bright *relative* to
/// the ~15-value background but only ~80-130 in absolute terms, so an absolute near-255 white test
/// (the original approach) misses it. The grey requirement (small channel spread) rejects coloured
/// tree art — green allocation glows and gold/green jewel-ring spokes — though a blown-out spoke core
/// can still read grey, which is why the caller also requires radial symmetry (a spoke is a stripe).
fn is_glow_px(r: i32, g: i32, b: i32) -> bool {
    let mx = r.max(g).max(b);
    let mn = r.min(g).min(b);
    r > 55 && g > 55 && b > 55 && (mx - mn) < 40
}

/// True if the node centred at (`cx`,`cy`) in physical px carries the search-highlight halo: a
/// grey glow is present in at least `GLOW_COVERAGE_MIN` of the directions around it (sampled at
/// several radii spanning the icon edge). Requiring glow in MOST directions is what separates the
/// radially-symmetric highlight from a bright spoke or a one-sided sunburst that only lights a
/// couple of directions. Robust to a few px of pose error and to icon_r being slightly off (a
/// direction is lit if any of its radii hits the halo). `icon_r` is the on-screen node-icon radius
/// in px (JS derives it from the locked ring radius × zoom).
fn glow_at(buf: &[u8], w: usize, h: usize, cx: f64, cy: f64, icon_r: f64) -> bool {
    use std::f64::consts::PI;
    if icon_r < 3.0 {
        return false;
    }
    let is_glow = |px: f64, py: f64| -> Option<bool> {
        let (ix, iy) = (px.round() as i64, py.round() as i64);
        if ix < 0 || iy < 0 || ix as usize >= w || iy as usize >= h {
            return None;
        }
        let i = (iy as usize * w + ix as usize) * 4;
        Some(is_glow_px(buf[i] as i32, buf[i + 1] as i32, buf[i + 2] as i32))
    };
    let (mut lit, mut on_screen) = (0usize, 0usize);
    for k in 0..GLOW_ANGLES {
        let a = 2.0 * PI * k as f64 / GLOW_ANGLES as f64;
        let (c, s) = (a.cos(), a.sin());
        let mut any_sample = false;
        let mut any_glow = false;
        for &m in &GLOW_RADII {
            let r = icon_r * m;
            if let Some(g) = is_glow(cx + r * c, cy + r * s) {
                any_sample = true;
                any_glow |= g;
            }
        }
        if any_sample {
            on_screen += 1;
        }
        if any_glow {
            lit += 1;
        }
    }
    // Need most directions on-screen (reject a node hanging off the frame edge) and most of them lit.
    on_screen >= GLOW_ANGLES * 3 / 4 && (lit as f64 / GLOW_ANGLES as f64) >= GLOW_COVERAGE_MIN
}

/// True if the captured frame still shows THIS overlay's own drawing. The overlay draws its target
/// ring in mask-safe ORANGE (#ff7733) and the hover ring in MAGENTA (#ff44dd) — colours deliberately
/// absent from the game (see the .node.target CSS note). Their presence means the overlay window
/// hadn't been cleared/presented when the capture ran (the capture raced the compositor). Crucially,
/// the overlay's white "to-do" node circles — which composite to a grey ring that mimics the search
/// halo and cause false glows — are drawn exactly when a target (orange) is, so orange is a reliable
/// proxy for "the interfering markers are on screen". Subsampled; a handful of pixels is enough.
fn frame_has_overlay(buf: &[u8], w: usize, h: usize) -> bool {
    let is_orange = |r: i32, g: i32, b: i32| r > 225 && (95..=150).contains(&g) && b < 80;
    let is_magenta = |r: i32, g: i32, b: i32| r > 225 && g < 110 && b > 190;
    let mut count = 0usize;
    let mut y = 0usize;
    while y < h {
        let row = y * w * 4;
        let mut x = 0usize;
        while x < w {
            let i = row + x * 4;
            let (r, g, b) = (buf[i] as i32, buf[i + 1] as i32, buf[i + 2] as i32);
            if is_orange(r, g, b) || is_magenta(r, g, b) {
                count += 1;
                if count >= 15 {
                    return true;
                }
            }
            x += 4;
        }
        y += 4;
    }
    false
}

/// Capture the primary monitor and report, for each candidate screen position (physical px), whether
/// that node has the search-highlight halo (see `glow_at`). `icon_r` is the expected node-icon radius
/// in px (the JS side derives it from the locked ring radius × zoom). The JS side hides the overlay
/// before calling, but the OS capture can race the compositor and still grab a frame with the overlay
/// drawn — whose white "to-do" node rings read as grey halos and light up nearly every node. So we
/// re-capture until the overlay sentinel (`frame_has_overlay`) is gone, then detect on that clean
/// frame. This is the core of the search-sweep capture method.
#[tauri::command]
fn detect_glow(positions: Vec<[f64; 2]>, icon_r: f64) -> Result<Vec<bool>, String> {
    let (mut frame, mut w, mut h) = capture_primary()?;
    for _ in 0..8 {
        if !frame_has_overlay(&frame, w as usize, h as usize) {
            break;
        }
        std::thread::sleep(std::time::Duration::from_millis(25));
        let cap = capture_primary()?;
        frame = cap.0;
        w = cap.1;
        h = cap.2;
    }
    let (wu, hu) = (w as usize, h as usize);
    Ok(positions
        .iter()
        .map(|p| glow_at(&frame, wu, hu, p[0], p[1], icon_r))
        .collect())
}

