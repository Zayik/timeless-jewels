// A recorded transform: which base node (in which socket, for which seed) became which
// result notable, with the OCR match confidence. Submission-ready (resultId is the DB
// vocab id); keyed seed:socket:baseSkill so multiple seeds/sockets accumulate until export.
interface RecordedTransform {
  jewel: string;
  conqueror: string;
  seed: number;
  socketId: number;
  baseSkill: number;
  /** String node id (DB tree_notables.node_id) — the identifier submitted as node_id. */
  nodeId: string;
  baseName: string;
  resultId: string;
  resultName: string;
  confidence: number;
  /** True once this observation has been accepted by the server. */
  synced: boolean;
  /** Quarantined: the server permanently rejected this row (bad FK / seed out of
   *  range), so it's excluded from auto-retry to stop it blocking and spamming. */
  failed?: boolean;
}
const recorded = new Map<string, RecordedTransform>();
// Keyed by (seed, node) — NOT socket: a timeless jewel's transform for a node depends only
// on the seed, so a node shared by overlapping sockets is recorded once and shows as done in
// every socket (matches the DB's seed+node uniqueness). source_socket is kept as metadata.
const recordKey = (seed: number, skill: number): string => `${seed}:${skill}`;
const isRecorded = (skill: number): boolean =>
  !!jewelInfo && recorded.has(recordKey(jewelInfo.seed, skill));

// Community consensus for the current seed, keyed by string node_id (tree_notables.node_id).
// Loaded from the Worker when a jewel is read, so the overlay can show what others already
// recorded and avoid redoing verified nodes.
let dbConsensus = new Map<string, { confirmations: number; verified: boolean }>();
// Track the fetch outcome so we never report "you're first" when we simply couldn't reach
// the DB (e.g. offline, or the overlay is running a build without the fetch_consensus command).
let dbState: 'idle' | 'loading' | 'loaded' | 'error' = 'idle';
let dbError = '';
const communityVerified = (n: Notable): boolean => dbConsensus.get(n.id)?.verified === true;
const communityPartial = (n: Notable): boolean => {
  const c = dbConsensus.get(n.id);
  return !!c && !c.verified;
};
// "Covered" = genuinely done, skip it: you recorded it this session, OR it's already verified
// (>=2 sources). A SINGLE unverified community record is NOT covered — it behaves like a fresh
// node (orange target, hover-focus, auto-record) so you can add the verifying 2nd source; the
// only difference is the "needs verify" annotation.
const isCovered = (n: Notable): boolean => isRecorded(n.skill) || communityVerified(n);

// Node name annotated with its community status, so it's clear at the point of recording
// whether someone already captured it (and whether that capture is verified yet).
function nodeLabel(n: Notable): string {
  if (isRecorded(n.skill)) return `${n.name} · recorded by you`;
  const c = dbConsensus.get(n.id);
  if (!c) return n.name;
  return c.verified ? `${n.name} · verified` : `${n.name} · recorded ×${c.confirmations}, needs verify`;
}

// --- contribution sync ---
// Writes go to the Cloudflare Worker (which holds the DB credential); the overlay never
// touches the DB directly. The POST is made from the Rust side (reqwest) because the
// webview CSP blocks cross-origin fetch — see submit_observations in main.rs.
const WORKER_BASE = 'https://timeless-jewels-proxy.davidleeanderson1991.workers.dev';
const RECORDS_KEY = 'poe2_overlay_records';
const CLIENT_KEY = 'poe2_overlay_client_id';
// A stable anonymous contributor id so consensus can count distinct contributors and
// re-recording the same node overwrites our own vote (DB upserts on jewel/seed/node/client).
const clientId: string =
  localStorage.getItem(CLIENT_KEY) ??
  (() => {
    const id = crypto.randomUUID();
    localStorage.setItem(CLIENT_KEY, id);
    return id;
  })();
let syncing = false;

function saveRecords(): void {
  localStorage.setItem(RECORDS_KEY, JSON.stringify([...recorded.entries()]));
}
function loadRecords(): void {
  try {
    const raw = localStorage.getItem(RECORDS_KEY);
    if (!raw) return;
    // Re-key under the current scheme (recordKey from the stored value) so records saved
    // under an older key format still load and dedupe correctly.
    for (const [, v] of JSON.parse(raw) as [string, RecordedTransform][]) {
      recorded.set(recordKey(v.seed, v.baseSkill), v);
    }
  } catch {
    /* corrupt store — start fresh */
  }
}
const pendingSync = (): number => {
  let n = 0;
  for (const r of recorded.values()) if (!r.synced && !r.failed) n++;
  return n;
};
const failedSync = (): number => {
  let n = 0;
  for (const r of recorded.values()) if (!r.synced && r.failed) n++;
  return n;
};

// Cap each POST well under the server's hourly budget so one flush can't trip the
// throttle in a single shot, and so a rejected batch only forces row-by-row retry
// over a small slice rather than the whole backlog.
const SYNC_CHUNK = 200;
// When the server reports its hourly limit, stop hammering it: pause all syncing for
// this long, then resume from where we left off (the window will have moved on).
const THROTTLE_BACKOFF_MS = 5 * 60 * 1000;
let backoffUntil = 0;

// The Worker surfaces the DB throttle (PT429) as "HTTP 400: …rate limit exceeded…".
const isThrottle = (msg: string): boolean => /rate limit|PT429|\b429\b/i.test(msg);

async function postObservations(batch: [string, RecordedTransform][]): Promise<void> {
  const observations = batch.map(([, r]) => ({
    jewel_type: r.jewel,
    conqueror: r.conqueror || null,
    seed: r.seed,
    node_id: r.nodeId,
    result_notable_id: r.resultId,
    source_socket: r.socketId
  }));
  const body = JSON.stringify({ client_id: clientId, observations });
  await invoke('submit_observations', { workerUrl: WORKER_BASE, body });
}

// Push not-yet-synced observations to the Worker in capped chunks. Idempotent upserts
// make retries safe. A whole chunk is one DB transaction that aborts if any single row
// is rejected, so on chunk failure we fall back to row-by-row: valid rows land and only
// genuinely-bad rows are quarantined (failed=true) instead of blocking the backlog
// forever. Throttle responses pause syncing rather than spin.
async function flushSync(): Promise<void> {
  if (syncing || Date.now() < backoffUntil) return;
  const pending = [...recorded.entries()].filter(([, r]) => !r.synced && !r.failed);
  if (pending.length === 0) return;
  syncing = true;
  try {
    for (let i = 0; i < pending.length; i += SYNC_CHUNK) {
      const chunk = pending.slice(i, i + SYNC_CHUNK);
      try {
        await postObservations(chunk);
        for (const [, r] of chunk) r.synced = true;
        saveRecords();
      } catch (e) {
        if (isThrottle(String(e))) {
          backoffUntil = Date.now() + THROTTLE_BACKOFF_MS;
          return; // resume on a later interval, once the hourly window has moved
        }
        // One bad row aborted the chunk's transaction. Retry each row alone so the
        // rest still sync and only the offender is quarantined.
        for (const entry of chunk) {
          try {
            await postObservations([entry]);
            entry[1].synced = true;
          } catch (e2) {
            if (isThrottle(String(e2))) {
              backoffUntil = Date.now() + THROTTLE_BACKOFF_MS;
              saveRecords();
              return;
            }
            entry[1].failed = true; // permanent rejection (bad FK / seed range)
            console.warn('observation rejected:', entry[1], String(e2));
          }
        }
        saveRecords();
      }
    }
  } finally {
    syncing = false;
    updateSyncStatus();
  }
}
function updateSyncStatus(): void {
  const total = recorded.size;
  if (total === 0) {
    syncEl.textContent = '';
    syncEl.className = 'ok';
    return;
  }
  const pending = pendingSync();
  const failed = failedSync();
  const parts = [`synced ${total - pending - failed}/${total}`];
  if (pending) parts.push(Date.now() < backoffUntil ? `${pending} pending (paused)` : `${pending} pending`);
  if (failed) parts.push(`${failed} rejected`);
  syncEl.textContent = parts.join(' · ');
  syncEl.className = pending || failed ? 'warn' : 'ok';
}

// Pull the community consensus for a (jewel, seed) so already-recorded nodes are shown and
// verified ones skipped — avoids redoing a jewel someone else already mapped. Best-effort:
// offline / not-found just leaves the map empty and recording proceeds as normal.
async function loadConsensus(jewel: string, seed: number): Promise<void> {
  dbConsensus = new Map();
  dbState = 'loading';
  dbError = '';
  updateDbInfo();
  try {
    const raw = (await invoke('fetch_consensus', { workerUrl: WORKER_BASE, jewel, seed })) as string;
    const data = JSON.parse(raw) as {
      results?: Array<{ node_id: string; confirmations: number; verified: boolean }>;
    };
    for (const r of data.results ?? []) {
      dbConsensus.set(r.node_id, { confirmations: r.confirmations, verified: r.verified });
    }
    dbState = 'loaded';
  } catch (e) {
    // DO NOT fall back to "you're first" — that would be a lie. Surface the real failure.
    dbState = 'error';
    dbError = String(e);
  }
  updateDbInfo();
  resetTargetToFirstUnrecorded();
  if (active && lockedPose) renderLocked();
}

function updateDbInfo(): void {
  if (!jewelInfo) {
    dbInfoEl.textContent = '';
    dbInfoEl.className = 'muted';
    return;
  }
  if (dbState === 'loading') {
    dbInfoEl.textContent = 'Checking community records…';
    dbInfoEl.className = 'muted';
    return;
  }
  if (dbState === 'error') {
    dbInfoEl.textContent = `Community DB unreachable — ${dbError} (records still save & retry).`;
    dbInfoEl.className = 'warn';
    return;
  }
  if (dbConsensus.size === 0) {
    dbInfoEl.textContent = 'Community: no records for this seed yet — you’re first.';
    dbInfoEl.className = 'community';
    return;
  }
  let verified = 0;
  for (const c of dbConsensus.values()) if (c.verified) verified++;
  const partial = dbConsensus.size - verified;
  // Lead with the unverified count — with sparse testing that's the common, important case.
  dbInfoEl.textContent =
    partial > 0
      ? `Community (seed ${jewelInfo.seed}): ${partial} recorded but UNVERIFIED (need a 2nd capture)` +
        `${verified ? `, ${verified} verified` : ''}.`
      : `Community (seed ${jewelInfo.seed}): all ${verified} verified.`;
  dbInfoEl.className = 'community';
}

